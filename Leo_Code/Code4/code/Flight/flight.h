#pragma once

#include <iostream>

#include "clock.h"

class Flight {
public:
    // constructors
    Flight(int n);
    Flight(int n, const Clock& d, const Clock& a);

    Flight(const Flight& f) = default;  // use the default copy constructor generated by the
                                        // compiler -- shallow copy

    // Destructor
    // use the default destructor generated by the compiler
    ~Flight() = default;
    /*
    // Destructor generated by the compiler
    ~Flight() {
        dep.~Clock();
        arr.~Clock();
    }
    */

    Flight& operator=(const Flight& f) =
        default;  // use the default assignment operator -- shallow copy

    // Overloaded stream insertion operator  -- lecture 7
    friend std::ostream& operator<<(std::ostream& os, const Flight& f);

private:
    int number;  // flight's number
    Clock dep;   // flight's departure time
    Clock arr;   // flight's arrival time
};
